package tagger

import "math"

// 자체 코퍼스 IDF — "이 사용자의 저장 목록에서 이 낱말이 얼마나 변별력이 있는가".
//
// 규칙 태거의 남은 오탐은 대부분 **흔한 표면**에서 나온다. `ai`·`ml`·`go`처럼 짧은 alias는
// 토큰 동등 매칭으로도 정당한 문장에 스쳐 들어가고, 개발 링크만 저장하는 사용자에게
// `dev`는 거의 모든 문서에 붙어 아무것도 구분해 주지 않는다. 둘 다 사전을 손봐서는 못 고친다 —
// **어느 낱말이 흔한지는 사용자마다 다르기 때문이다.** 축구 기사를 모으는 사람에게 `축구`는
// 변별력이 없고 `쿠버네티스`는 강하며, 개발자에게는 정확히 반대다.
//
// 그래서 외부 코퍼스를 쓰지 않는다. 저장된 링크 자체가 코퍼스다(스펙 05 corpus_df).
//
// **태그가 아니라 표면(term) 단위로 잰다.** 한 태그에 `go`와 `golang`이 같이 달려 있을 때
// 둘의 변별력은 전혀 다른데, 태그 단위로 재면 그 차이가 사라진다.
const (
	// idfFloor는 가장 흔한 낱말이 받는 최소 배율. 0이 아닌 이유: 모든 문서에 나오는
	// 낱말도 여전히 증거다 — 약할 뿐이다. 0으로 두면 사용자의 주력 주제 태그가
	// **자기 코퍼스에서만** 사라지는, 설명하기 어려운 동작이 된다.
	idfFloor = 0.35
	// minCorpusDocs는 IDF를 켜기 위한 최소 문서 수. 문서 몇 건에서 나온 DF는 통계가 아니라
	// 잡음이고, 그 잡음으로 가중치를 흔들면 갓 시작한 사용자가 가장 나쁜 태깅을 받는다.
	// 이 아래에서는 배율이 전부 1.0 — IDF가 없던 때와 **정확히** 같이 동작한다.
	minCorpusDocs = 50
)

// CorpusStats는 자체 코퍼스의 문서 빈도 스냅샷. store가 읽어 넘긴다(태거는 store를 모른다).
// DF는 **사전 표면에 대해서만** 센다 — 스코어링이 쓰는 것이 그것뿐이다.
type CorpusStats struct {
	Docs int64            // 코퍼스 문서 수. minCorpusDocs 미만이면 IDF 비활성
	DF   map[string]int64 // 표면 → 그 표면이 나타난 문서 수 (없는 키는 0)
}

// idfMul은 표면 하나의 가중치 배율을 [idfFloor, 1.0]에서 돌려준다.
//
// **코퍼스가 붙지 않은 사전에서는 항상 1.0이다.** 이것이 지금의 기본 상태다 — 2026-07-26
// 시점에 이 배율은 어디서도 켜지지 않았고, 그 이유는 켤 근거를 만들 수 없었기 때문이다:
// golden은 42개 태그에 60건씩 층화 샘플링한 세트라 **어떤 표면도 문서의 38%를 넘지 않고**
// (실측: dev 최대 0.34, test 0.38), 편중이 없는 코퍼스에서 IDF는 정의상 할 일이 없다.
// 실제 저장 코퍼스는 그때 3건이었다. 자세한 경위는 nlu/golden/README.md.
//
// 그래서 순서를 뒤집었다: 먼저 corpus_df를 **모으고**, 코퍼스가 실물이 된 뒤에 이 배율을
// 사전에 붙여 measure한다. 그 전에 켜는 것은 측정 없이 품질을 바꾸는 일이다.
func (d *Dictionary) idfMul(surface string) float64 {
	if d.corpus.Docs < minCorpusDocs {
		return 1.0
	}
	n := float64(d.corpus.Docs)
	df := float64(d.corpus.DF[surface])
	// log((N+1)/(df+1))을 최댓값 log(N+1)로 나눠 [0,1]로 만든다.
	// df=0 → 1.0(가장 희귀), df=N → 0에 가까움(모든 문서에 등장).
	raw := math.Log((n+1)/(df+1)) / math.Log(n+1)
	return idfFloor + (1-idfFloor)*raw
}
